//! Константы аутентификации кадров, вынесенные из приватного модуля `net`
//! родительского проекта — здесь нужны только эти два значения, без остальной
//! оркестрации туннеля.

/// Шаг TOTP-подобного окна аутентификации, секунды.
pub const AUTH_TIME_STEP: u64 = 60;

/// Сколько соседних окон допускается (защита от рассинхрона часов), в обе стороны.
pub const AUTH_WINDOW_SIZE: u64 = 2;

/// Текущая версия схемы вывода ключей (аутентифицированная, два DH).
pub const PROTOCOL_VERSION: u8 = 3;

/// Версия для стороны без учётных данных ноды (один DH, без аутентификации).
pub const PROTOCOL_VERSION_ANONYMOUS: u8 = 2;

/// Минимальная заявленная версия клиента для аутентифицированной схемы (второй DH).
pub const MIN_VERSION_FOR_STATIC_DH: u8 = 3;
