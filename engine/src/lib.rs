//! # netrunner-tls-engine — публичное «ядро маскировки» Netrunner
//!
//! Извлечено из приватного монорепозитория `netrunner-proxy` вместе с двумя
//! модулями, без которых оно физически не собирается: [`crypto`] (обмен
//! ключами/AEAD — `tlseng` встраивает в поля фальшивого TLS-хендшейка
//! реальный ключевой материал) и небольшие generic-утилиты ([`parser`],
//! [`errors`], [`utils::u24`], [`net_consts`]).
//!
//! **Чего здесь нет специально:** реального протокола кадрирования NRXP,
//! мультиплексора туннеля (`net`) и приложенческой логики сервера/клиента —
//! они остаются в приватном ядре. Откалиброванные JA3/JA4-профили браузеров
//! в [`tlseng::profile`] заменены плейсхолдерами (см. комментарий в файле) —
//! это осознанное решение, а не недосмотр: раскрытие точных калибровок дало
//! бы DPI готовый чек-лист сигнатур.

pub mod bridge;
pub mod crypto;
pub mod errors;
mod net_consts;
pub mod nrxp;
pub mod parser;
pub mod tlseng;
pub mod utils;

pub use crypto::{Identity, LocalIdentity, PeerIdentity};
