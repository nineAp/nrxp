//! Эфемерный обмен ключами по схеме X25519 (Elliptic-Curve Diffie-Hellman).
//!
//! Один экземпляр [`ECDH`] обслуживает ровно один хендшейк: на старте генерится
//! эфемерная пара ключей, публичная половина уходит в `ClientHello`/`ServerHello`,
//! а приватная уничтожается сразу после вывода ключей сессии ([`ECDH::burn`]).
//! Это и есть механизм forward secrecy: даже компрометация долговременных
//! секретов в будущем не расшифрует записанный ранее трафик.
//!
//! ## Почему `StaticSecret`, а не `EphemeralSecret`
//!
//! Начиная с версии протокола 3 одним и тем же эфемерным ключом делается **два**
//! DH: с эфемерным ключом пира (forward secrecy) и с его долговременным
//! статическим ключом (аутентификация сервера, см.
//! [`identity`](super::identity)). `EphemeralSecret::diffie_hellman` забирает
//! `self` по значению, поэтому второй раз вызван быть не может — тип физически
//! не даёт выразить схему.
//!
//! Эфемерность при этом никуда не делась, она просто обеспечивается не типом, а
//! временем жизни: ключ существует только внутри хендшейка и стирается явным
//! [`burn`](ECDH::burn) сразу после `generate_keys` (`StaticSecret` у
//! `x25519-dalek` — `ZeroizeOnDrop`, так что память затирается, а не просто
//! освобождается). Ни одна ветка не должна оставлять `ECDH` живым после
//! хендшейка.

use aead::OsRng;
use x25519_dalek::{PublicKey, StaticSecret};

/// Состояние одной стороны ECDH-обмена.
///
/// `private_key` обёрнут в [`Option`], потому что приватная половина
/// уничтожается по завершении хендшейка ([`ECDH::burn`]). После этого
/// [`ECDH::dh`] возвращает `None` — попытка посчитать общий секрет на
/// отработавшем состоянии не тихая ошибка, а явный отказ.
#[allow(clippy::upper_case_acronyms)]
pub(crate) struct ECDH {
    /// Публичный ключ, который отправляется удалённой стороне в KeyShare.
    pub public_key: PublicKey,
    /// Приватный эфемерный ключ. `Some` до [`burn`](ECDH::burn), затем `None`.
    private_key: Option<StaticSecret>,
}

impl ECDH {
    /// Генерирует свежую эфемерную пару ключей из системного ГСЧ ([`OsRng`]).
    pub(crate) fn new() -> Self {
        let secret = StaticSecret::random_from_rng(OsRng);
        let public = PublicKey::from(&secret);
        Self {
            private_key: Some(secret),
            public_key: public,
        }
    }

    /// Вычисляет общий секрет с публичным ключом удалённой стороны, **не**
    /// расходуя приватный ключ: за один хендшейк метод вызывается один раз (v2)
    /// или два (v3, второй — со статическим ключом пира).
    ///
    /// Возвращает `None` после [`burn`](ECDH::burn).
    pub(crate) fn dh(&self, public: &PublicKey) -> Option<[u8; 32]> {
        let shared = self.private_key.as_ref()?.diffie_hellman(public);
        Some(*shared.as_bytes())
    }

    /// Уничтожает приватный ключ. Вызывается ровно один раз — сразу после того,
    /// как все ключи сессии выведены (см. `SessionKeys::generate_keys`).
    ///
    /// **Инвариант forward secrecy:** после выхода из хендшейка приватного
    /// эфемерного ключа не должно существовать ни в одной живой структуре.
    pub(crate) fn burn(&mut self) {
        self.private_key = None;
    }
}
