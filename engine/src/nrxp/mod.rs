//! # Формат кадра NRXP и его крипто-слои (частично открытая копия)
//!
//! Этот модуль — публичная копия большей части протокола кадрирования NRXP:
//! формат кадра, шифрующий кодек TCP-ноги (батчинг, выравнивание длин записи)
//! и датаграммный AEAD-кодек UDP-ноги (реконструкция счётчика, ratchet-ключи,
//! анти-replay окно). Мультиплексор потоков (`Muxer`, распределение по
//! локальным сокетам, диагностика) сюда не входит — только кадрирование и
//! крипто-слой одного направления.
//!
//! **Отредактировано перед публикацией:** ровно 6 калиброванных чисел заменены
//! плейсхолдерами — см. `REDACTED FOR PUBLIC RELEASE` в [`codec`] (параметры
//! выравнивания длины записи) и [`datagram`] (порог ratchet-перевыпуска ключа,
//! размер окна анти-replay). Это единственное, что здесь скрыто: сам механизм
//! (батчинг, инвариант «кадр не режется границей записи», реконструкция
//! счётчика по RFC 9000/RFC 3711, скользящее окно в духе WireGuard) — код как
//! он есть, потому что раскрытие того, *что* делает протокол, не помогает его
//! обойти; раскрытие *точных чисел* — помогает строить детектор по трафику.
//!
//! ## Формат кадра (25-байтовый заголовок + payload + padding)
//!
//! ```text
//! ┌──────────────┬───────────┬──────┬────────────┬────────────┬─────────┬─────────┐
//! │ Auth Tag     │ Stream ID │ Type │ Payload Len│ Padding Len│ Payload │ Padding │
//! │ 16 байт      │ 4 байта   │ 1 б. │ 2 байта    │ 2 байта    │ N байт  │ 0..255  │
//! └──────────────┴───────────┴──────┴────────────┴────────────┴─────────┴─────────┘
//! ```
//!
//! Этот заголовок целиком лежит **внутри** AEAD-шифрования — на проводе (без
//! ключей) не видно даже того, что именно тут показано. Публикация его формата
//! не даёт наблюдателю ничего, чего не даёт уже сам факт «это зашифрованная
//! запись TLS ApplicationData».

pub mod codec;
pub mod datagram;
pub mod frame;

pub use codec::{Codec, RxCodec, TxCodec};
pub(crate) use datagram::{truncate_counter, DatagramRx, DatagramTx};
pub(crate) use frame::{Frame, FrameType};
pub use frame::{FRAME_HEADER_SIZE, MAX_FRAME_PAYLOAD, MAX_RECORD_PLAINTEXT};
